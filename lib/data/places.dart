const _customPrefix = 'custom:';

/// Stored form of a place typed in by hand: `custom:lat;lon;zone`.
String customPlace(double lat, double lon, String zone) =>
    '$_customPrefix$lat;$lon;$zone';

/// Resolves a stored place: a list label (or bare Polish name) or a hand-typed `custom:` entry.
Place? placeNamed(String? stored) {
  if (stored == null) return null;
  if (stored.startsWith(_customPrefix)) {
    final p = stored.substring(_customPrefix.length).split(';');
    if (p.length != 3) return null;
    final lat = double.tryParse(p[0]), lon = double.tryParse(p[1]);
    if (lat == null || lon == null || !isZone(p[2])) return null;
    return (name: '$lat°, $lon°', country: null, lat: lat, lon: lon, tz: p[2]);
  }
  for (final c in cities) {
    if (placeLabel(c) == stored) return c;
  }
  return null;
}

var _tzReady = false;
void _initTz() {
  if (!_tzReady) {
    tzdata.initializeTimeZones();
    _tzReady = true;
  }
}

/// All IANA zone ids known offline, sorted (for the "other place" picker).
List<String> allZones() {
  _initTz();
  return tz.timeZoneDatabase.locations.keys.toList()..sort();
}

bool isZone(String id) {
  _initTz();
  return tz.timeZoneDatabase.locations.containsKey(id);
}

/// Civil time at a place → UTC, using the tz database history (incl. old summer-time rules).
DateTime localToUtc(CalendarDate d, int minutes, String zone) {
  _initTz();
  final t = tz.TZDateTime(
    tz.getLocation(zone),
    d.year,
    d.month,
    d.day,
    minutes ~/ 60,
    minutes % 60,
  );
  return DateTime.fromMillisecondsSinceEpoch(
    t.millisecondsSinceEpoch,
    isUtc: true,
  );
}

DateTime warsawToUtc(CalendarDate d, int minutes) =>
    localToUtc(d, minutes, 'Europe/Warsaw');
